impl TryFrom<SubscribeResponseBody> for SubscribeResult {
    type Error = PubNubError;

    fn try_from(value: SubscribeResponseBody) -> Result<Self, Self::Error> {
        match value {
            SubscribeResponseBody::SuccessResponse(resp) => {
                let mut messages = Vec::new();
                for message in resp.messages {
                    if let SubscribeMessageType::Unknown(event_type) = &message.message_type {
                        log::debug!("Unknown event type ({}) has been received", event_type);
                        continue;
                    }

                    messages.push(message.try_into()?)
                }

                Ok(SubscribeResult {
                    cursor: resp.cursor,
                    messages,
                })
            }
            SubscribeResponseBody::ErrorResponse(resp) => Err(resp.into()),
        }
    }
}

/// Single entry from subscribe response as it is received.
///
/// Payload is kept as raw JSON until channel and event type are known.
#[cfg(feature = "serde")]
#[derive(serde::Deserialize)]
struct EnvelopeRaw {
    #[serde(rename = "a")]
    shard: String,

    #[serde(rename = "f")]
    debug_flags: u32,

    #[serde(rename = "e", default = "Envelope::default_message_type")]
    message_type: SubscribeMessageType,

    #[serde(rename = "i", default)]
    sender: Option<String>,

    #[serde(rename = "s", default)]
    sequence_number: Option<u32>,

    #[serde(rename = "p")]
    published: SubscriptionCursor,

    #[serde(rename = "c")]
    channel: String,

    #[serde(rename = "d")]
    payload: serde_json::Value,

    #[serde(rename = "b", default)]
    subscription: Option<String>,

    #[serde(rename = "cmt", default)]
    custom_message_type: Option<String>,

    #[serde(rename = "u")]
    user_metadata: Option<serde_json::Value>,
}

#[cfg(feature = "serde")]
impl TryFrom<EnvelopeRaw> for Envelope {
    type Error = PubNubError;

    fn try_from(value: EnvelopeRaw) -> Result<Self, Self::Error> {
        let payload =
            EnvelopePayload::from_raw(&value.channel, &value.message_type, value.payload)?;

        Ok(Self {
            shard: value.shard,
            debug_flags: value.debug_flags,
            message_type: value.message_type,
            sender: value.sender,
            sequence_number: value.sequence_number,
            published: value.published,
            channel: value.channel,
            payload,
            subscription: value.subscription,
            custom_message_type: value.custom_message_type,
            user_metadata: value.user_metadata,
        })
    }
}

#[cfg(feature = "serde")]
impl Envelope {
    /// Default message type.
    fn default_message_type() -> SubscribeMessageType {
        SubscribeMessageType::Message
    }
}

#[cfg(feature = "serde")]
impl EnvelopePayload {
    /// Select payload variant using event type and channel.
    ///
    /// Event type is checked first. Presence is detected only for events
    /// without known event type and received on `-pnpres` channel. Everything
    /// else which doesn't match is a message.
    fn from_raw(
        channel: &str,
        message_type: &SubscribeMessageType,
        payload: serde_json::Value,
    ) -> Result<Self, PubNubError> {
        match message_type {
            SubscribeMessageType::Message if channel.ends_with("-pnpres") => {
                match <Self as serde::Deserialize>::deserialize(&payload) {
                    Ok(
                        presence @ (Self::PresenceStateChange { .. }
                        | Self::PresenceAnnounce { .. }
                        | Self::PresenceInterval { .. }),
                    ) => Ok(presence),
                    _ => Ok(Self::Message(payload)),
                }
            }
            SubscribeMessageType::Message
            | SubscribeMessageType::Signal
            | SubscribeMessageType::Unknown(_) => Ok(Self::Message(payload)),
            SubscribeMessageType::Object
            | SubscribeMessageType::MessageAction
            | SubscribeMessageType::File => {
                let parsed =
                    <Self as serde::Deserialize>::deserialize(&payload).map_err(|error| {
                        PubNubError::Deserialization {
                            details: error.to_string(),
                        }
                    })?;

                match (message_type, &parsed) {
                    (SubscribeMessageType::Object, Self::Object { .. })
                    | (SubscribeMessageType::MessageAction, Self::MessageAction { .. })
                    | (SubscribeMessageType::File, Self::File { .. }) => Ok(parsed),
                    _ => Err(PubNubError::Deserialization {
                        details: "Payload doesn't match event type".to_string(),
                    }),
                }
            }
        }
    }
}

#[cfg(feature = "std")]
impl Update {
    /// Name of subscription.
    ///
    /// Name of channel or channel group on which client subscribed and through
    /// which real-time update has been delivered.
    pub(crate) fn subscription(&self) -> String {
        match self {
            Self::Presence(presence) => presence.subscription(),
            Self::AppContext(object) => object.subscription(),
            Self::MessageAction(reaction) => reaction.subscription.clone(),
            Self::File(file) => file.subscription.clone(),
            Self::Message(message) | Self::Signal(message) => message.subscription.clone(),
        }
    }

    /// PubNub high-precision event timestamp.
    ///
    /// # Returns
    ///
    /// Returns time when event has been emitted.
    pub(crate) fn event_timestamp(&self) -> usize {
        match self {
            Self::Presence(presence) => presence.event_timestamp(),
            Self::AppContext(object) => object.event_timestamp(),
            Self::MessageAction(reaction) => reaction.timestamp,
            Self::File(file) => file.timestamp,
            Self::Message(message) | Self::Signal(message) => message.timestamp,
        }
    }
}

impl TryFrom<Envelope> for Update {
    type Error = PubNubError;

    fn try_from(value: Envelope) -> Result<Self, Self::Error> {
        match value.payload {
            EnvelopePayload::PresenceAnnounce { .. }
            | EnvelopePayload::PresenceInterval { .. }
            | EnvelopePayload::PresenceStateChange { .. } => {
                Ok(Update::Presence(value.try_into()?))
            }
            EnvelopePayload::Object { .. }
                if matches!(value.message_type, SubscribeMessageType::Object) =>
            {
                Ok(Update::AppContext(value.try_into()?))
            }
            EnvelopePayload::MessageAction { .. }
                if matches!(value.message_type, SubscribeMessageType::MessageAction) =>
            {
                Ok(Update::MessageAction(value.try_into()?))
            }
            EnvelopePayload::File { .. }
                if matches!(value.message_type, SubscribeMessageType::File) =>
            {
                Ok(Update::File(value.try_into()?))
            }
            EnvelopePayload::Message(_) => {
                if matches!(value.message_type, SubscribeMessageType::Message) {
                    Ok(Update::Message(value.try_into()?))
                } else {
                    Ok(Update::Signal(value.try_into()?))
                }
            }
            _ => Err(PubNubError::Deserialization {
                details: "Unable deserialize unknown payload".to_string(),
            }),
        }
    }
}

impl From<EnvelopePayload> for Vec<u8> {
    #[cfg(feature = "serde")]
    fn from(value: EnvelopePayload) -> Self {
        if let EnvelopePayload::Message(payload) = value {
            return serde_json::to_vec(&payload).unwrap_or_default();
        }
        vec![]
    }

    #[cfg(not(feature = "serde"))]
    fn from(value: EnvelopePayload) -> Self {
        if let EnvelopePayload::Message(payload) = value {
            return payload;
        }
        vec![]
    }
}

